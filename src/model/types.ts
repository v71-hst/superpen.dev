// Loose typings for the .pen document format (see pen-schema.md). Unknown keys are preserved on save.
export type PenNode = {
  type: string;
  id: string;
  name?: string;
  children?: PenNode[];
  [key: string]: any;
};

export type VariableDef = { type: 'color' | 'number' | 'string' | 'boolean'; value: any };

export type PenDoc = {
  version: string;
  children: PenNode[];
  variables?: Record<string, VariableDef>;
  themes?: Record<string, string[]>;
  imports?: Record<string, string>;
  [key: string]: any;
};

export type Theme = Record<string, string>;

/** Where an on-canvas node lives: a real document node, or a node generated by expanding a ref. */
export type NodeSource =
  | { kind: 'real'; id: string }
  | { kind: 'virtual'; instanceId: string; path: string };

/** A node after ref expansion; `props` are merged but variables are still unresolved. */
export type RNode = {
  key: string;
  type: string;
  props: PenNode;
  src: NodeSource;
  theme: Theme;
  children: RNode[];
  /** Set on the root of an expanded ref. */
  instanceOf?: string;
  isComponent: boolean;
  /** True when this node is inside an instance (not directly editable as a document node). */
  inInstance: boolean;
  /** Key of the containing instance root, when inInstance. */
  instanceKey?: string;
  /** Produced by a script node (read-only output). */
  generated?: boolean;
};
