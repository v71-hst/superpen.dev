// Agent-facing document operations (atomic batches) and compact read views (outline, search, node JSON).
import type { PenDoc, PenNode, RNode } from './types';
import { allIds, cloneWithNewIds, displayName, indexDoc, locate, newId } from './doc';
import { applyProps, keySource } from '../editor/store';
import { isGeneratedKey } from './resolve';

export const NODE_TYPES = new Set([
  'frame', 'group', 'rectangle', 'ellipse', 'polygon', 'path', 'line', 'text', 'note', 'prompt', 'context', 'icon', 'icon_font', 'script', 'browser', 'ref',
]);
const CONTAINERS = new Set(['frame', 'group']);

export type Operation =
  | { op: 'insert'; parent?: string | null; index?: number; node: PenNode }
  | { op: 'update'; id: string; props: Record<string, any> }
  | { op: 'delete'; id: string }
  | { op: 'move'; id: string; parent?: string | null; index?: number; x?: number; y?: number }
  | { op: 'duplicate'; id: string; parent?: string | null; index?: number; props?: Record<string, any> }
  | { op: 'replace'; id: string; node: PenNode }
  | { op: 'instantiate'; component: string; parent?: string | null; index?: number; props?: Record<string, any>; overrides?: Record<string, any> };

export type OpResult = { op: string; id?: string; ids?: string[]; note?: string };

class OpError extends Error {}

function fail(i: number, msg: string): never {
  throw new OpError(`operation ${i}: ${msg}`);
}

/** Gives every node in a tree a valid unique id (keeping caller-provided ids when they are free). */
function assignIds(node: PenNode, ids: Set<string>, i: number) {
  if (!node || typeof node !== 'object') fail(i, 'node must be an object');
  if (!node.type || !NODE_TYPES.has(node.type)) fail(i, `unknown node type "${node.type}". Valid: ${[...NODE_TYPES].join(', ')}`);
  if (typeof node.id === 'string' && node.id && !node.id.includes('/') && !ids.has(node.id)) ids.add(node.id);
  else {
    node.id = newId(ids);
    ids.add(node.id);
  }
  if (node.type === 'ref' && typeof node.ref !== 'string') fail(i, 'ref nodes need a "ref" (component id)');
  if (node.children !== undefined) {
    if (!Array.isArray(node.children)) fail(i, '"children" must be an array');
    if (!CONTAINERS.has(node.type) && node.type !== 'ref') fail(i, `${node.type} nodes cannot have children`);
    node.children.forEach(c => assignIds(c, ids, i));
  }
}

function childList(d: PenDoc, parent: string | null | undefined, i: number): PenNode[] {
  if (parent === null || parent === undefined || parent === '') return d.children;
  if (parent.includes('/')) fail(i, `cannot insert into "${parent}": it is inside a component instance (edit the component, or use "update" with overrides)`);
  const loc = locate(d, parent);
  if (!loc) fail(i, `parent "${parent}" not found`);
  if (!CONTAINERS.has(loc.node.type) && !(loc.node.type === 'ref' && Array.isArray(loc.node.children))) fail(i, `parent "${parent}" is a ${loc.node.type}; only frames and groups can contain children`);
  return (loc.node.children ??= []);
}

function cleanProps(props: Record<string, any>) {
  const out: Record<string, any> = {};
  for (const [k, v] of Object.entries(props ?? {})) {
    if (k === 'id' || k === 'type' || k === 'children') continue;
    out[k] = v === null ? undefined : v;
  }
  return out;
}

function insertAt(list: PenNode[], node: PenNode, index: number | undefined) {
  if (index === undefined || index < 0 || index >= list.length) list.push(node);
  else list.splice(index, 0, node);
}

function existsKey(d: PenDoc, key: string): boolean {
  if (isGeneratedKey(key)) throw new OpError(`"${key}" is generated by a script and can't be edited directly; change the script node's inputs or the script file`);
  const src = keySource(key);
  return !!locate(d, src.kind === 'real' ? src.id : src.instanceId);
}

/** Applies a batch of operations to a draft document. Throws (leaving nothing applied) on the first invalid one. */
export function applyOperations(d: PenDoc, ops: Operation[]): { results: OpResult[]; touched: string[] } {
  if (!Array.isArray(ops)) throw new OpError('"operations" must be an array');
  const ids = allIds(d);
  const results: OpResult[] = [];
  const touched: string[] = [];
  ops.forEach((o: any, i) => {
    switch (o?.op) {
      case 'insert': {
        const node: PenNode = JSON.parse(JSON.stringify(o.node ?? null));
        assignIds(node, ids, i);
        insertAt(childList(d, o.parent, i), node, o.index);
        results.push({ op: 'insert', id: node.id });
        touched.push(node.id);
        break;
      }
      case 'update': {
        if (typeof o.id !== 'string') fail(i, 'update needs "id"');
        if (!existsKey(d, o.id)) fail(i, `node "${o.id}" not found`);
        const props = cleanProps(o.props);
        if (!Object.keys(props).length) fail(i, 'update needs non-empty "props"');
        applyProps(d, o.id, props);
        results.push({ op: 'update', id: o.id });
        touched.push(o.id);
        break;
      }
      case 'delete': {
        if (typeof o.id !== 'string') fail(i, 'delete needs "id"');
        const src = keySource(o.id);
        if (src.kind === 'virtual') {
          if (!existsKey(d, o.id)) fail(i, `node "${o.id}" not found`);
          applyProps(d, o.id, { enabled: false });
          results.push({ op: 'delete', id: o.id, note: 'inside an instance: hidden via override (enabled: false)' });
        } else {
          const loc = locate(d, o.id);
          if (!loc) fail(i, `node "${o.id}" not found`);
          loc.siblings.splice(loc.index, 1);
          results.push({ op: 'delete', id: o.id });
        }
        break;
      }
      case 'move': {
        if (typeof o.id !== 'string' || o.id.includes('/')) fail(i, 'move needs the "id" of a document node (not inside an instance)');
        const loc = locate(d, o.id);
        if (!loc) fail(i, `node "${o.id}" not found`);
        if (o.parent !== undefined) {
          if (o.parent && (o.parent === o.id || isInside(d, o.parent, o.id))) fail(i, 'cannot move a node into itself');
          const list = childList(d, o.parent, i);
          loc.siblings.splice(loc.index, 1);
          insertAt(list, loc.node, o.index);
        } else if (o.index !== undefined) {
          loc.siblings.splice(loc.index, 1);
          insertAt(loc.siblings, loc.node, o.index);
        }
        if (typeof o.x === 'number') loc.node.x = o.x;
        if (typeof o.y === 'number') loc.node.y = o.y;
        results.push({ op: 'move', id: o.id });
        touched.push(o.id);
        break;
      }
      case 'duplicate': {
        if (typeof o.id !== 'string' || o.id.includes('/')) fail(i, 'duplicate needs the "id" of a document node');
        const loc = locate(d, o.id);
        if (!loc) fail(i, `node "${o.id}" not found`);
        const copy = cloneWithNewIds(loc.node, ids);
        Object.assign(copy, cleanProps(o.props ?? {}));
        for (const [k, v] of Object.entries(copy)) if (v === undefined) delete copy[k];
        if (o.parent !== undefined) insertAt(childList(d, o.parent, i), copy, o.index);
        else loc.siblings.splice(o.index ?? loc.index + 1, 0, copy);
        results.push({ op: 'duplicate', id: copy.id });
        touched.push(copy.id);
        break;
      }
      case 'replace': {
        if (typeof o.id !== 'string' || o.id.includes('/')) fail(i, 'replace needs the "id" of a document node');
        const loc = locate(d, o.id);
        if (!loc) fail(i, `node "${o.id}" not found`);
        const node: PenNode = JSON.parse(JSON.stringify(o.node ?? null));
        ids.delete(o.id);
        node.id = node.id ?? o.id;
        assignIds(node, ids, i);
        loc.siblings[loc.index] = node;
        results.push({ op: 'replace', id: node.id });
        touched.push(node.id);
        break;
      }
      case 'instantiate': {
        if (typeof o.component !== 'string') fail(i, 'instantiate needs "component" (id of a reusable node)');
        const comp = locate(d, o.component);
        if (!comp) fail(i, `component "${o.component}" not found`);
        if (!comp.node.reusable) fail(i, `node "${o.component}" is not a component (set reusable: true on it first)`);
        const id = newId(ids);
        ids.add(id);
        const node: PenNode = { type: 'ref', id, ref: o.component, ...cleanProps(o.props ?? {}) };
        for (const [k, v] of Object.entries(node)) if (v === undefined) delete node[k];
        if (o.overrides && typeof o.overrides === 'object') node.descendants = o.overrides;
        insertAt(childList(d, o.parent, i), node, o.index);
        results.push({ op: 'instantiate', id });
        touched.push(id);
        break;
      }
      default:
        fail(i, `unknown op "${o?.op}". Valid: insert, update, delete, move, duplicate, replace, instantiate`);
    }
  });
  return { results, touched };
}

function isInside(d: PenDoc, id: string, ancestorId: string): boolean {
  const idx = indexDoc(d);
  let p = idx.parentOf.get(id);
  while (p) {
    if (p.id === ancestorId) return true;
    p = idx.parentOf.get(p.id) ?? null;
  }
  return false;
}

