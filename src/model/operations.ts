// ---------------- read views ----------------

const fmtN = (n: any) => (typeof n === 'number' ? String(Math.round(n * 100) / 100) : String(n));

function sizeStr(p: any) {
  if (p.width === undefined && p.height === undefined) return '';
  return ` ${fmtN(p.width ?? 'auto')}×${fmtN(p.height ?? 'auto')}`;
}

function paintStr(f: any): string {
  if (f === undefined) return '';
  const list = Array.isArray(f) ? f : [f];
  return list
    .map(x => (typeof x === 'string' ? x : x?.type === 'color' ? x.color : x?.type === 'gradient' ? `${x.gradientType ?? 'linear'}-gradient` : x?.type ?? '?'))
    .join('+');
}

/** One-line summary of a node, e.g. `frame "Card" #a1B2c 320×fit_content layout:vertical gap:12 fill:#FFF`. */
export function describe(n: RNode): string {
  const p = n.props;
  const parts = [n.instanceOf ? `instance of #${n.instanceOf}` : n.type];
  const name = p.name ?? (n.type === 'text' ? undefined : undefined);
  if (name) parts.push(JSON.stringify(name));
  parts.push(`#${n.key}`);
  if (n.isComponent) parts.push('[component]');
  if (p.enabled === false) parts.push('[hidden]');
  if (typeof p.x === 'number' || typeof p.y === 'number') parts.push(`@${fmtN(p.x ?? 0)},${fmtN(p.y ?? 0)}`);
  const sz = sizeStr(p);
  if (sz) parts.push(sz.trim());
  if (n.type === 'frame') {
    const l = p.layout ?? 'horizontal';
    parts.push(`layout:${l}`);
    if (p.gap) parts.push(`gap:${fmtN(p.gap)}`);
    if (p.padding !== undefined) parts.push(`padding:${JSON.stringify(p.padding)}`);
    if (p.clip) parts.push('clip');
  }
  if (n.type === 'text') {
    const c = typeof p.content === 'string' ? p.content : '';
    parts.push(JSON.stringify(c.length > 60 ? c.slice(0, 57) + '…' : c));
    parts.push(`${fmtN(p.fontSize ?? 14)}px ${p.fontFamily ?? 'Inter'}${p.fontWeight ? ' ' + p.fontWeight : ''}`);
  }
  if (n.type === 'icon' || n.type === 'icon_font') parts.push(`${p.library ?? p.iconFontFamily ?? 'lucide'}:${p.icon ?? p.iconFontName}`);
  if (n.type === 'script') parts.push(`script:${p.scriptUri ?? '(none)'}${p.inputs ? ' inputs:' + JSON.stringify(p.inputs) : ''} → ${n.children.length} generated node(s)`);
  const shaderFill = (Array.isArray(p.fill) ? p.fill : [p.fill]).find((f: any) => f?.type === 'shader');
  if (shaderFill) parts.push(`shader-fill:${shaderFill.url}`);
  const shaderFx = (Array.isArray(p.effect) ? p.effect : [p.effect]).filter((e: any) => e?.type === 'shader').map((e: any) => e.url);
  if (shaderFx.length) parts.push(`shader-effect:${shaderFx.join(',')}`);
  if (p.fill !== undefined && n.type !== 'icon') parts.push(`fill:${paintStr(p.fill)}`);
  if (p.stroke !== undefined) parts.push(`stroke:${paintStr(p.stroke?.fill ?? p.stroke)}`);
  return parts.join(' ');
}

export function outline(roots: RNode[], depth: number, expandInstances: boolean): string {
  const lines: string[] = [];
  const walk = (nodes: RNode[], level: number) => {
    for (const n of nodes) {
      lines.push(`${'  '.repeat(level)}- ${describe(n)}`);
      if (!n.children.length || n.type === 'script') continue;
      if (n.instanceOf && !expandInstances && level > 0) {
        lines.push(`${'  '.repeat(level + 1)}… ${n.children.length} child node(s) from the component (expand_instances to show)`);
      } else if (level + 1 >= depth) {
        lines.push(`${'  '.repeat(level + 1)}… ${countAll(n)} more node(s) (increase depth or pass root_id #${n.key})`);
      } else walk(n.children, level + 1);
    }
  };
  walk(roots, 0);
  return lines.join('\n');
}

function countAll(n: RNode): number {
  return n.children.reduce((s, c) => s + 1 + countAll(c), 0);
}

/** Raw node JSON with children truncated below `depth` levels. */
export function nodeJson(doc: PenDoc, tree: { byKey: Map<string, RNode> }, key: string, depth: number): any {
  const src = keySource(key);
  let node: any;
  if (src.kind === 'real') node = locate(doc, src.id)?.node;
  else node = tree.byKey.get(key)?.props;
  if (!node) return null;
  const trim = (n: any, level: number): any => {
    if (!n || typeof n !== 'object') return n;
    const out: any = { ...n };
    if (Array.isArray(n.children)) {
      out.children = level >= depth ? `… ${n.children.length} children (request with a larger depth or by id)` : n.children.map((c: any) => trim(c, level + 1));
    }
    return out;
  };
  const out = trim(node, 0);
  if (src.kind === 'virtual') out._note = 'Inside a component instance; updates are stored as overrides on the instance.';
  return out;
}

export function searchNodes(tree: { byKey: Map<string, RNode>; parent: Map<string, RNode | null> }, query: string, type: string | undefined, limit: number, rootKey?: string): string[] {
  const q = (query ?? '').toLowerCase();
  const out: string[] = [];
  for (const n of tree.byKey.values()) {
    if (type && n.type !== type && !(type === 'instance' && n.instanceOf)) continue;
    if (rootKey) {
      let p: RNode | null | undefined = n;
      let inside = false;
      while (p) {
        if (p.key === rootKey) inside = true;
        p = tree.parent.get(p.key);
      }
      if (!inside) continue;
    }
    const hay = [n.key, displayName(n.props), typeof n.props.content === 'string' ? n.props.content : '', n.props.icon ?? ''].join('\n').toLowerCase();
    if (q && !hay.includes(q)) continue;
    const path: string[] = [];
    let p = tree.parent.get(n.key);
    while (p) {
      path.unshift(displayName(p.props));
      p = tree.parent.get(p.key);
    }
    out.push(`${describe(n)}${path.length ? `  (in ${path.join(' › ')})` : ''}`);
    if (out.length >= limit) break;
  }
  return out;
}
